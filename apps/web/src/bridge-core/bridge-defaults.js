export const V46_FAMILIES = Object.freeze(['aqueduct', 'viaduct']);

export function getV46FamilyPreset(family) {
  if (!V46_FAMILIES.includes(family)) throw new RangeError(`Unsupported bridge family: ${String(family)}`);
  return structuredClone({ ...V46_COMMON_SETTINGS, ...V46_FAMILY_PRESETS[family], family });
}

export function getV46DefaultSettings(family = 'aqueduct') {
  return getV46FamilyPreset(family);
}
