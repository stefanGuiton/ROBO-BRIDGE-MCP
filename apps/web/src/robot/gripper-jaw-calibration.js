export function frameForJawGap(gapMm) {
  const samples = GRIPPER_JAW_GAP_SAMPLES;
  if (gapMm <= samples[0][1]) return samples[0][0];
  if (gapMm >= samples.at(-1)[1]) return samples.at(-1)[0];
  let low = 0;
  let high = samples.length - 1;
  while (high - low > 1) {
    const middle = (low + high) >> 1;
    if (samples[middle][1] <= gapMm) low = middle; else high = middle;
  }
  const amount = (gapMm - samples[low][1]) / (samples[high][1] - samples[low][1]);
  return samples[low][0] + (samples[high][0] - samples[low][0]) * amount;
}

export function jawGapForFrame(frame) {
  const index = Math.max(0, Math.min(240, frame * 4));
  const low = Math.floor(index);
  const high = Math.min(240, Math.ceil(index));
  const amount = index - low;
  return GRIPPER_JAW_GAP_SAMPLES[low][1] * (1 - amount) + GRIPPER_JAW_GAP_SAMPLES[high][1] * amount;
}
